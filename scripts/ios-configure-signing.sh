#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IOS_DIR="${ROOT_DIR}/apps/ios"
TEAM_ID_SCRIPT="${ROOT_DIR}/scripts/ios-team-id.sh"
LOCAL_SIGNING_FILE="${IOS_DIR}/.local-signing.xcconfig"
CANONICAL_TEAM_ID="FWJYW4S8P8"

sanitize_identifier_segment() {
  local raw="${1:-}"
  raw="$(printf '%s' "$raw" | tr '[:upper:]' '[:lower:]')"
  raw="$(printf '%s' "$raw" | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//; s/-+/-/g')"
  if [[ -z "$raw" ]]; then
    raw="local"
  fi
  printf '%s\n' "$raw"
}

normalize_bundle_id() {
  local raw="${1:-}"
  raw="$(printf '%s' "$raw" | tr '[:upper:]' '[:lower:]')"
  raw="$(printf '%s' "$raw" | sed -E 's/[^a-z0-9.-]+/-/g; s/\.+/./g; s/^-+//; s/[.-]+$//')"
  if [[ -z "$raw" ]]; then
    raw="ai.aforafoundation.app.test.local"
  fi
  printf '%s\n' "$raw"
}

if [[ ! -x "${TEAM_ID_SCRIPT}" ]]; then
  echo "ERROR: Missing team detection helper: ${TEAM_ID_SCRIPT}" >&2
  exit 1
fi

team_id=""
if team_id="$("${TEAM_ID_SCRIPT}" 2>/dev/null)"; then
  :
else
  if [[ "${IOS_SIGNING_REQUIRED:-0}" == "1" ]]; then
    "${TEAM_ID_SCRIPT}"
    exit 1
  fi

  echo "WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any)." >&2
  exit 0
fi

if [[ -n "${AFORA_IOS_BUNDLE_SUFFIX:-}" ]]; then
  identity_source="${AFORA_IOS_BUNDLE_SUFFIX}"
else
  identity_source="${USER:-}"
  if [[ -z "${identity_source}" ]]; then
    identity_source="$(id -un 2>/dev/null || true)"
  fi
  team_segment="$(sanitize_identifier_segment "${team_id}")"
  identity_source="${identity_source}-${team_segment}"
fi
bundle_suffix="$(sanitize_identifier_segment "${identity_source}")"

bundle_base="${AFORA_IOS_APP_BUNDLE_ID:-${AFORA_IOS_BUNDLE_ID_BASE:-}}"
if [[ -z "${bundle_base}" ]]; then
  if [[ "${team_id}" == "${CANONICAL_TEAM_ID}" ]]; then
    bundle_base="ai.aforafoundation.app"
  else
    bundle_base="ai.aforafoundation.app.test.${bundle_suffix}"
  fi
fi
bundle_base="$(normalize_bundle_id "${bundle_base}")"

share_bundle_id="${AFORA_IOS_SHARE_BUNDLE_ID:-${bundle_base}.share}"
app_group_id="${AFORA_IOS_APP_GROUP_ID:-group.${bundle_base}.shared}"
activity_widget_bundle_id="${AFORA_IOS_ACTIVITY_WIDGET_BUNDLE_ID:-${bundle_base}.activitywidget}"
watch_app_bundle_id="${AFORA_IOS_WATCH_APP_BUNDLE_ID:-${bundle_base}.watchkitapp}"

code_sign_style="${AFORA_IOS_CODE_SIGN_STYLE:-Automatic}"
code_sign_identity="${AFORA_IOS_CODE_SIGN_IDENTITY:-Apple Development}"
apns_entitlement_environment="${AFORA_IOS_APNS_ENTITLEMENT_ENVIRONMENT:-development}"
app_profile="${AFORA_IOS_APP_PROFILE:-}"
share_profile="${AFORA_IOS_SHARE_PROFILE:-}"
activity_widget_profile="${AFORA_IOS_ACTIVITY_WIDGET_PROFILE:-}"
watch_app_profile="${AFORA_IOS_WATCH_APP_PROFILE:-}"

tmp_file="$(mktemp "${TMPDIR:-/tmp}/afora-ios-configure-signing.XXXXXX")"
cat >"${tmp_file}" <<EOF
// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// IOS_DEVELOPMENT_TEAM / IOS_PREFERRED_TEAM_ID
// AFORA_IOS_APP_BUNDLE_ID / AFORA_IOS_BUNDLE_ID_BASE
// AFORA_IOS_SHARE_BUNDLE_ID / AFORA_IOS_APP_GROUP_ID
// AFORA_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// AFORA_IOS_WATCH_APP_BUNDLE_ID
// AFORA_IOS_CODE_SIGN_STYLE / AFORA_IOS_CODE_SIGN_IDENTITY
// AFORA_IOS_APNS_ENTITLEMENT_ENVIRONMENT / AFORA_IOS_APP_PROFILE
// AFORA_IOS_SHARE_PROFILE / AFORA_IOS_ACTIVITY_WIDGET_PROFILE
// AFORA_IOS_WATCH_APP_PROFILE
AFORA_CODE_SIGN_STYLE = ${code_sign_style}
AFORA_CODE_SIGN_IDENTITY = ${code_sign_identity}
AFORA_CODE_SIGN_ENTITLEMENTS = Sources/Afora.entitlements
AFORA_DEVELOPMENT_TEAM = ${team_id}
// Keep legacy key for compatibility with older signing config paths.
AFORA_IOS_SELECTED_TEAM = ${team_id}
AFORA_APP_BUNDLE_ID = ${bundle_base}
AFORA_SHARE_BUNDLE_ID = ${share_bundle_id}
AFORA_APP_GROUP_ID = ${app_group_id}
AFORA_ACTIVITY_WIDGET_BUNDLE_ID = ${activity_widget_bundle_id}
AFORA_WATCH_APP_BUNDLE_ID = ${watch_app_bundle_id}
AFORA_APNS_ENTITLEMENT_ENVIRONMENT = ${apns_entitlement_environment}
AFORA_APP_PROFILE = ${app_profile}
AFORA_SHARE_PROFILE = ${share_profile}
AFORA_ACTIVITY_WIDGET_PROFILE = ${activity_widget_profile}
AFORA_WATCH_APP_PROFILE = ${watch_app_profile}
EOF

if [[ -f "${LOCAL_SIGNING_FILE}" ]] && cmp -s "${tmp_file}" "${LOCAL_SIGNING_FILE}"; then
  rm -f "${tmp_file}"
  echo "iOS signing config already up to date: team=${team_id} app=${bundle_base}"
  exit 0
fi

mv "${tmp_file}" "${LOCAL_SIGNING_FILE}"
if [[ "${team_id}" == "${CANONICAL_TEAM_ID}" ]]; then
  echo "Configured iOS signing: team=${team_id} app=${bundle_base}"
else
  echo "Configured iOS local signing: canonical_team=${CANONICAL_TEAM_ID} local_team=${team_id} app=${bundle_base}"
fi
